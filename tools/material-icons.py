ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data/icons/material"
RUST = ROOT / "src/theme/icons.rs"


def main() -> None:
    font = TTFont(sys.argv[1] if len(sys.argv) > 1 else FONT)
    # Optical size 20 suits GTK's 16 px icons; a little heavier than regular, as thin strokes fade at that size.
    font = instancer.instantiateVariableFont(font, {"FILL": 0, "GRAD": 0, "opsz": 20, "wght": 500})
    glyphs = font.getGlyphSet()
    size = font["head"].unitsPerEm
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.svg"):
        old.unlink()
    for name, symbol in sorted(ICONS.items()):
        if symbol not in glyphs:
            sys.exit(f"Material Symbols has no {symbol!r} (for {name})")
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        # Font units grow upwards; SVG's grow down.
        glyphs[symbol].draw(TransformPen(pen, (1, 0, 0, -1, 0, size)))
        svg = (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 {size} {size}">'
            f'<path fill="#2e3436" d="{pen.getCommands()}"/></svg>\n'
        )
        (OUT / f"{name}.svg").write_text(svg)
    lines = [
        "// Generated by tools/material-icons.py; don't edit.",
        "",
        "/// Each icon name the app asks for, and its Material Symbols SVG.",
        "pub const ICONS: &[(&str, &str)] = &[",
    ]
    for name in sorted(ICONS):
        lines.append(f'    ("{name}", include_str!("../../data/icons/material/{name}.svg")),')
    lines.append("];")
    RUST.parent.mkdir(parents=True, exist_ok=True)
    RUST.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
